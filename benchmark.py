def simulate_solution(sol_schedule, config):
    sim = TumorSimulator(days=config.days,
                         patient_profile=config.patient_profile,
                         subtype_scores=config.subtype_scores)
    t, pop_tx   = sim.simulate_treatment(sol_schedule)
    _, pop_notx = sim.simulate_no_treatment()
    final_notx  = pop_notx[-1]
    final_tx    = pop_tx[-1]
    reduction   = (final_notx - final_tx) / max(final_notx, 1e-9) * 100.0
    tox = sum(get_effective_toxicity(d, config) * np.sum(sol_schedule[d])
              for d in sol_schedule)
    eff = sum(DEFAULT_DRUG_LIBRARY.get(d, {}).get("efficacy", 0) * np.sum(sol_schedule[d])
              for d in sol_schedule)
    return t, pop_tx, pop_notx, reduction, tox, eff


def run_all(config):
    results = {}

    print("\n" + "="*60)
    print("  Q-DOS BENCHMARK ??? Patient Scenario")
    print("="*60)

    methods = [
        ("Standard Care",       lambda c: generate_standard_care(c)),
        ("Greedy",              lambda c: generate_greedy(c)),
        ("Random",              lambda c: generate_random(c, seed=42)),
        ("Simulated Annealing", lambda c: generate_simulated_annealing(c)),
    ]

    # Brute Force
    bf_possible = len(config.selected_drugs) * config.days <= 16
    if bf_possible:
        methods.append(("Brute Force", generate_brute_force))

    # Q-DOS
    print("\n[1/6] Running Q-DOS (Quantum QUBO)...")
    t0 = time.perf_counter()
    try:
        qdos_sol = run_optimization(config)
        qdos_ok  = qdos_sol.status == "SUCCESS"
    except Exception as e:
        print(f"  ??? Q-DOS failed: {e}")
        qdos_ok = False
    qdos_time = time.perf_counter() - t0

    if qdos_ok:
        t_arr, pop_tx, pop_notx, red, tox, eff = simulate_solution(qdos_sol.schedule, config)
        results["Q-DOS"] = {
            "schedule": qdos_sol.schedule,
            "per_day":  qdos_sol.per_day_drugs,
            "t": t_arr, "tumor": pop_tx, "notx": pop_notx,
            "reduction": red, "toxicity": tox, "efficacy": eff,
            "solve_time": qdos_time, "objective": qdos_sol.metrics.get("score", 0.0),
        }
        print(f"  ??? Q-DOS  reduction={red:.1f}%  tox={tox:.2f}  time={qdos_time:.2f}s")

    # Baselines
    for i, (name, fn) in enumerate(methods, 2):
        print(f"\n[{i}/{len(methods)+1}] Running {name}...")
        t0 = time.perf_counter()
        try:
            sol = fn(config)
            if sol is None:
                print(f"  ??? {name} skipped (too large)"); continue
            t_arr, pop_tx, pop_notx, red, tox, eff = simulate_solution(sol.schedule, config)
            elapsed = time.perf_counter() - t0
            results[name] = {
                "schedule": sol.schedule,
                "per_day":  sol.per_day_drugs,
                "t": t_arr, "tumor": pop_tx, "notx": pop_notx,
                "reduction": red, "toxicity": tox, "efficacy": eff,
                "solve_time": elapsed, "objective": _objective(sol.schedule, config),
            }
            print(f"  ??? {name}  reduction={red:.1f}%  tox={tox:.2f}  time={elapsed:.3f}s")
        except Exception as e:
            print(f"  ??? {name} error: {e}")

    return results


