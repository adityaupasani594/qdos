def run_mc_comparison(config, n=20, seed=0):
    from statistics_engine import run_monte_carlo
    print(f"\n  Running Monte Carlo (N={n}) ??? this may take 1-2 min...")
    report = run_monte_carlo(config, n=n, seed=seed, confidence=0.95)
    strategies = [s.strategy for s in report.schedules]
    means  = [s.mean_tumor_reduction for s in report.schedules]
    ci_lo  = [s.ci_low  for s in report.schedules]
    ci_hi  = [s.ci_high for s in report.schedules]
    colors = [PALETTE.get(s, "#888") for s in strategies]

    fig, ax = plt.subplots(figsize=(10, 5))
    x = np.arange(len(strategies))
    bars = ax.bar(x, means, color=colors, edgecolor="white", alpha=0.9)
    ax.errorbar(x, means,
                yerr=[np.array(means) - np.array(ci_lo),
                      np.array(ci_hi) - np.array(means)],
                fmt="none", color="#1e293b", capsize=6, lw=2)
    for bar, val in zip(bars, means):
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.3,
                f"{val:.1f}%", ha="center", fontsize=9)
    ax.set_xticks(x); ax.set_xticklabels(strategies)
