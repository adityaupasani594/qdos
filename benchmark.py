def _objective(schedule, config):
    """Compute a scalar objective (lower = better) matching the QUBO spirit."""
    drugs = config.selected_drugs
    days  = config.days
    budget = config.base_toxicity_budget - 0.5 * (config.patient_profile.get("age", 40) - 40)

    efficacy = sum(
        DEFAULT_DRUG_LIBRARY.get(d, {}).get("efficacy", 0) * schedule[d][t]
        for d in drugs for t in range(days)
    )
    total_tox = sum(
        get_effective_toxicity(d, config) * schedule[d][t]
        for d in drugs for t in range(days)
    )
    tox_penalty = config.beta * (total_tox - budget) ** 2

    daily_pen = 0.0
    for t in range(days):
        n_today = sum(schedule[d][t] for d in drugs)
        excess  = max(0, n_today - config.max_drugs_per_day)
        daily_pen += config.lambda_daily * excess ** 2

    return -config.alpha * efficacy + tox_penalty + daily_pen


def generate_simulated_annealing(config: OptimizationConfig, seed=42):
    rng   = np.random.default_rng(seed)
    drugs = config.selected_drugs
    days  = config.days

    schedule = {d: np.zeros(days, int) for d in drugs}
    cur_obj  = _objective(schedule, config)

    T, T_min, alpha = 10.0, 0.001, 0.95
    best_schedule = deepcopy(schedule)
    best_obj      = cur_obj

    while T > T_min:
        d = rng.choice(drugs)
        t = rng.integers(0, days)
        schedule[d][t] ^= 1                     # flip bit
        new_obj = _objective(schedule, config)
        delta   = new_obj - cur_obj
        if delta < 0 or rng.random() < np.exp(-delta / T):
            cur_obj = new_obj
            if cur_obj < best_obj:
                best_obj      = cur_obj
                best_schedule = deepcopy(schedule)
        else:
            schedule[d][t] ^= 1                 # revert
        T *= alpha

    per_day = {t: [d for d in drugs if best_schedule[d][t] == 1]
               for t in range(days)}
    tox = sum(get_effective_toxicity(d, config) * best_schedule[d][t]
              for d in drugs for t in range(days))
    eff = sum(DEFAULT_DRUG_LIBRARY.get(d, {}).get("efficacy", 0) * best_schedule[d][t]
              for d in drugs for t in range(days))

    class _Sol:
        schedule     = best_schedule
        per_day_drugs= per_day
        strategy     = "Simulated Annealing"
        total_toxicity = tox
        total_efficacy = eff
    return _Sol()


