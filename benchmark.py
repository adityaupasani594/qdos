def generate_brute_force(config: OptimizationConfig):
    drugs = config.selected_drugs
    days  = config.days
    n_vars = len(drugs) * days
    if n_vars > 16:
        return None

    best_obj = float("inf")
    best_bits = None
    for bits in itertools.product([0, 1], repeat=n_vars):
        schedule = {}
        idx = 0
        for d in drugs:
            schedule[d] = np.array(bits[idx: idx + days], int)
            idx += days
        obj = _objective(schedule, config)
        if obj < best_obj:
            best_obj  = obj
            best_bits = bits

    schedule = {}
    idx = 0
    for d in drugs:
        schedule[d] = np.array(best_bits[idx: idx + days], int)
        idx += days
    per_day = {t: [d for d in drugs if schedule[d][t] == 1] for t in range(days)}
    tox = sum(get_effective_toxicity(d, config) * schedule[d][t]
              for d in drugs for t in range(days))
    eff = sum(DEFAULT_DRUG_LIBRARY.get(d, {}).get("efficacy", 0) * schedule[d][t]
              for d in drugs for t in range(days))

    class _Sol:
        pass
    s = _Sol()
    s.schedule      = schedule
    s.per_day_drugs = per_day
    s.strategy      = "Brute Force"
    s.total_toxicity= tox
    s.total_efficacy= eff
    return s


